const defaultSyncParallelism = "8"

// syncConfigBlobPrefix is the prefix shared by the repository-wide configuration
// blobs (format blob, blobcfg, maintenance schedule, format backups).
const syncConfigBlobPrefix = "kopia."

// syncPhase determines the order in which blobs are copied to the destination.
//
// Blobs are copied phase by phase and a phase starts only after every copy in
// the previous phase has succeeded, so an interrupted sync never leaves the
// destination with an index that references a pack it does not have, or with
// a format blob that describes data that has not arrived yet.
type syncPhase int

const (
	syncPhaseData          syncPhase = iota // packs and anything not listed below
	syncPhaseIndex                          // index blobs, epoch markers and sessions
	syncPhaseIndexMetadata                  // v0 compaction logs and cleanup markers, which refer to index blobs
	syncPhaseConfig                         // kopia.* configuration blobs except the format blob
	syncPhaseFormat                         // kopia.repository, written last
	numSyncPhases
)

// syncDeletePhaseOrder deletes blobs that reference other blobs before the
// blobs they reference, so the destination stays readable if deletion is
// interrupted.
var syncDeletePhaseOrder = []syncPhase{syncPhaseIndexMetadata, syncPhaseIndex, syncPhaseConfig, syncPhaseData}

//nolint:gochecknoglobals
var (
	syncIndexPrefixes = []string{
		indexblob.V0IndexBlobPrefix,
		epoch.EpochManagerIndexUberPrefix,
		string(content.BlobIDPrefixSession),
	}
	syncIndexMetadataPrefixes = []string{
		indexblob.V0CompactionLogBlobPrefix,
		indexblob.V0CleanupBlobPrefix,
	}
)

func syncPhaseOf(id blob.ID) syncPhase {
	s := string(id)

	switch {
	case s == format.KopiaRepositoryBlobID:
		return syncPhaseFormat
	case strings.HasPrefix(s, syncConfigBlobPrefix):
		return syncPhaseConfig
	case hasAnyPrefix(s, syncIndexPrefixes):
		return syncPhaseIndex
	case hasAnyPrefix(s, syncIndexMetadataPrefixes):
		return syncPhaseIndexMetadata
	default:
		return syncPhaseData
	}
}

// syncNonDataPrefixes returns the listing prefixes that together cover every
// blob whose phase is not syncPhaseData.
func syncNonDataPrefixes() []blob.ID {
	var result []blob.ID

	result = append(result, syncConfigBlobPrefix)

	for _, p := range syncIndexPrefixes {
		result = append(result, blob.ID(p))
	}

	for _, p := range syncIndexMetadataPrefixes {
		result = append(result, blob.ID(p))
	}

	return result
}

// syncListAlphabet holds every character a blob ID generated by kopia can
// start with: prefixes are letters, "kopia." or "_log_", and content-derived
// names are hex.
const syncListAlphabet = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ_-."

// syncMaxListParallelism bounds concurrent list calls against one storage.
const syncMaxListParallelism = 16

// syncListShards returns disjoint listing prefixes that together cover every
// blob ID starting with a character in syncListAlphabet, except those starting
// with a character in skip. Pack prefixes, which hold nearly all blobs, are
// split further by their second character (in practice the first hex digit of
// the pack name). A blob ID consisting of a lone pack prefix is never created.
func syncListShards(skip string) []blob.ID {
	var result []blob.ID

	for _, ch := range syncListAlphabet {
		if strings.ContainsRune(skip, ch) {
			continue
		}

		if slices.Contains(content.PackBlobIDPrefixes, blob.ID(ch)) {
			for _, second := range syncListAlphabet {
				result = append(result, blob.ID(string(ch)+string(second)))
			}

			continue
		}

		result = append(result, blob.ID(ch))
	}

	return result
}

// syncFirstPassChars returns the leading characters whose blobs are all
// listed by the first source pass, so the second pass can skip them.
func syncFirstPassChars() string {
	var result string

	for _, p := range syncNonDataPrefixes() {
		if len(p) == 1 {
			result += string(p)
		}
	}

	return result
}

// listBlobsParallel lists each prefix, several at a time. The callback must
// be safe for concurrent use.
func listBlobsParallel(ctx context.Context, st blob.Reader, prefixes []blob.ID, cb func(blob.Metadata) error) error {
	eg, ctx := errgroup.WithContext(ctx)
	eg.SetLimit(syncMaxListParallelism)

	for _, prefix := range prefixes {
		eg.Go(func() error {
			return errors.Wrapf(st.ListBlobs(ctx, prefix, cb), "prefix %q", prefix)
		})
	}

	return eg.Wait() //nolint:wrapcheck
}

func hasAnyPrefix(s string, prefixes []string) bool {
	for _, p := range prefixes {
		if strings.HasPrefix(s, p) {
			return true
		}
	}

	return false
}

// syncBlobInfo is the compact form of blob.Metadata kept for every listed
// blob, so that listing very large repositories does not need gigabytes of RAM.
type syncBlobInfo struct {
	length    int64
	timestamp int64 // UnixNano
}

func newSyncBlobInfo(bm blob.Metadata) syncBlobInfo {
	return syncBlobInfo{length: bm.Length, timestamp: bm.Timestamp.UnixNano()}
}

type syncSourceBlob struct {
	id   blob.ID
	info syncBlobInfo
}

func (b syncSourceBlob) metadata() blob.Metadata {
	return blob.Metadata{BlobID: b.id, Length: b.info.length, Timestamp: time.Unix(0, b.info.timestamp)}
}

type commandRepositorySyncTo struct {
	nextSyncOutputTime timetrack.Throttle

	repositorySyncUpdate               bool
	repositorySyncDelete               bool
	repositorySyncDryRun               bool
	repositorySyncParallelism          uint
	repositorySyncDestinationMustExist bool
	repositorySyncTimes                bool

	// set when the destination rejects an option, so it is not sent again.
	timesUnsupported     atomic.Bool
	retentionUnsupported atomic.Bool
	timesWarning         sync.Once
	retentionWarning     sync.Once

	// the most recent progress message, formatted only when it is printed.
	lastSyncProgressMsg  string
	lastSyncProgressArgs []any
	lastSyncProgressLen  int
	syncProgressMutex    sync.Mutex

	out      textOutput
	progress *cliProgress
}

func (c *commandRepositorySyncTo) setup(svc advancedAppServices, parent commandParent) {
	cmd := parent.Command("sync-to", "Synchronizes the contents of this repository to another location")
	cmd.Flag("update", "Whether to update blobs present in destination and source if the source is newer.").Default(trueStr).BoolVar(&c.repositorySyncUpdate)
	cmd.Flag("delete", "Whether to delete blobs present in destination but not source.").BoolVar(&c.repositorySyncDelete)
	cmd.Flag("dry-run", "Do not perform copying.").Short('n').BoolVar(&c.repositorySyncDryRun)
	cmd.Flag("parallel", "Copy parallelism.").Default(defaultSyncParallelism).UintVar(&c.repositorySyncParallelism)
	cmd.Flag("must-exist", "Fail if destination does not have repository format blob.").BoolVar(&c.repositorySyncDestinationMustExist)
	cmd.Flag("times", "Synchronize blob times if supported.").BoolVar(&c.repositorySyncTimes)

	c.out.setup(svc)
	c.progress = svc.getProgress()

	for _, prov := range svc.storageProviders() {
		// Set up 'sync-to' subcommand
		f := prov.NewFlags()
		cc := cmd.Command(prov.Name, "Synchronize repository data to another repository in "+prov.Description)
		f.Setup(svc, cc)
		cc.Action(func(kpc *kingpin.ParseContext) error {
			return svc.runAppWithContext(kpc.SelectedCommand, func(ctx context.Context) error {
				st, err := f.Connect(ctx, false, 0)
				if err != nil {
					return errors.Wrap(err, "can't connect to storage")
				}

				defer st.Close(ctx) //nolint:errcheck

				// honor --max-upload-speed and the other limits given for the destination.
				st, err = repo.WrapWithConnectionThrottling(ctx, st)
				if err != nil {
					return errors.Wrap(err, "unable to apply destination throttling limits")
				}

				src, err := c.openSourceBlobs(ctx, svc)
				if err != nil {
					return err
				}

				defer src.Close(ctx) //nolint:errcheck

				blobcfg, err := src.FormatManager.BlobCfgBlob(ctx)
				if err != nil {
					return errors.Wrap(err, "unable to read blob storage configuration")
				}

				return c.runSyncWithStorage(ctx, src.Storage, st, blobcfg)
			})
		})
	}
}

// openSourceBlobs opens read-only blob access to the connected repository.
// Only raw blobs are copied, so the repository's indexes are not loaded.
func (c *commandRepositorySyncTo) openSourceBlobs(ctx context.Context, svc advancedAppServices) (*repo.BlobAccess, error) {
	configFile := svc.repositoryConfigFileName()

	if _, err := os.Stat(configFile); os.IsNotExist(err) {
		return nil, errors.New("repository is not connected. See https://kopia.io/docs/repositories/")
	}

	pass, err := svc.getPasswordFromFlags(ctx, false, true)
	if err != nil {
		return nil, errors.Wrap(err, "get password")
	}

	src, err := repo.OpenBlobAccess(ctx, configFile, pass, svc.optionsFromFlags(ctx))
	if err != nil {
		return nil, errors.Wrap(err, "open repository")
	}

	return src, nil
}

const syncProgressInterval = 300 * time.Millisecond

type syncPlan struct {
	toCopy        [numSyncPhases][]blob.Metadata
	numCopy       int
	copyBytes     int64
	toDelete      [numSyncPhases][]blob.Metadata
	numDelete     int
	deleteBytes   int64
	inSyncBlobs   int
	inSyncBytes   int64
	dstHasBlobs   bool
	configToCheck []blob.Metadata
}

func (p *syncPlan) addCopy(m blob.Metadata) {
	ph := syncPhaseOf(m.BlobID)
	p.toCopy[ph] = append(p.toCopy[ph], m)
	p.numCopy++
	p.copyBytes += m.Length
}

func (c *commandRepositorySyncTo) runSyncWithStorage(ctx context.Context, src blob.Reader, dst blob.Storage, blobcfg format.BlobStorageConfiguration) error {
	log(ctx).Info("Synchronizing repositories:")
	log(ctx).Infof("  Source:      %v", src.DisplayName())
	log(ctx).Infof("  Destination: %v", dst.DisplayName())

	if !c.repositorySyncDelete {
		log(ctx).Info("NOTE: By default no BLOBs are deleted, pass --delete to allow it.")
	}

	dstHasFormatBlob, err := c.ensureRepositoriesHaveSameFormatBlob(ctx, src, dst)
	if err != nil {
		return err
	}

	if !dstHasFormatBlob && c.repositorySyncDelete {
		return errors.New("destination does not contain a kopia repository, refusing to use --delete; run without --delete first")
	}

	log(ctx).Info("Looking for BLOBs to synchronize...")

	plan, err := c.buildSyncPlan(ctx, src, dst)
	if err != nil {
		return err
	}

	if !dstHasFormatBlob && plan.dstHasBlobs {
		log(ctx).Warn("WARNING: destination has no format blob but is not empty; it may contain data from an interrupted sync or unrelated files.")
	}

	if err := c.checkConfigBlobs(ctx, src, dst, plan); err != nil {
		return err
	}

	log(ctx).Infof(
		"  Found %v BLOBs to copy (%v), %v to delete (%v), %v in sync (%v)",
		plan.numCopy, units.BytesString(plan.copyBytes),
		plan.numDelete, units.BytesString(plan.deleteBytes),
		plan.inSyncBlobs, units.BytesString(plan.inSyncBytes),
	)

	if c.repositorySyncDryRun {
		return nil
	}

	log(ctx).Info("Copying...")

	c.beginSyncProgress()

	finalErr := c.runSyncBlobs(ctx, src, dst, plan, blobcfg)

	c.finishSyncProcess()

	return finalErr
}

// buildSyncPlan lists the source and destination concurrently and decides
// which blobs to copy and delete.
//
// The source is listed in two passes: first every prefix holding indexes and
// configuration, then everything else. Kopia writes a pack before any index
// that refers to it, so every pack referenced by an index seen in the first
// pass already exists when the second pass runs. Index and configuration blobs
// that appear only during the second pass are left for the next sync.
//
// Each listing is split into prefix shards listed in parallel, which keeps
// paginated cloud listings and deep directory walks from being serial.
//
//nolint:funlen
func (c *commandRepositorySyncTo) buildSyncPlan(ctx context.Context, src blob.Reader, dst blob.Storage) (*syncPlan, error) {
	var (
		dstMetadata = map[blob.ID]syncBlobInfo{}
		dstMu       sync.Mutex

		srcBlobs []syncSourceBlob
		srcMu    sync.Mutex

		srcCount, dstCount atomic.Int64
		srcBytes, dstBytes atomic.Int64
	)

	c.beginSyncProgress()

	showProgress := func() {
		c.outputSyncProgress("  Found %v BLOBs (%v) in the source, %v BLOBs (%v) in the destination",
			srcCount.Load(), units.BytesString(srcBytes.Load()),
			dstCount.Load(), units.BytesString(dstBytes.Load()))
	}

	var eg errgroup.Group

	eg.Go(func() error {
		return errors.Wrap(listBlobsParallel(ctx, dst, syncListShards(""), func(bm blob.Metadata) error {
			dstMu.Lock()
			dstMetadata[bm.BlobID] = newSyncBlobInfo(bm)
			dstMu.Unlock()

			dstCount.Add(1)
			dstBytes.Add(bm.Length)
			showProgress()

			return nil
		}), "error listing BLOBs in destination repository")
	})

	eg.Go(func() error {
		seen := map[blob.ID]bool{}

		add := func(sb syncSourceBlob) {
			srcMu.Lock()
			srcBlobs = append(srcBlobs, sb)
			srcMu.Unlock()

			if sb.info.length >= 0 {
				srcCount.Add(1)
				srcBytes.Add(sb.info.length)
				showProgress()
			}
		}

		if err := listBlobsParallel(ctx, src, syncNonDataPrefixes(), func(bm blob.Metadata) error {
			srcMu.Lock()
			seen[bm.BlobID] = true
			srcMu.Unlock()

			add(syncSourceBlob{bm.BlobID, newSyncBlobInfo(bm)})

			return nil
		}); err != nil {
			return errors.Wrap(err, "error listing index BLOBs in source repository")
		}

		// seen is read-only from here on. Shards whose leading character is fully
		// covered by the first pass are skipped.
		if err := listBlobsParallel(ctx, src, syncListShards(syncFirstPassChars()), func(bm blob.Metadata) error {
			switch {
			case seen[bm.BlobID]:
			case syncPhaseOf(bm.BlobID) != syncPhaseData:
				// appeared after the first pass; its packs may not be in this listing.
				log(ctx).Debugf("deferring %v to the next sync, it appeared during listing", bm.BlobID)
				add(syncSourceBlob{id: bm.BlobID, info: syncBlobInfo{length: -1}})
			default:
				add(syncSourceBlob{bm.BlobID, newSyncBlobInfo(bm)})
			}

			return nil
		}); err != nil {
			return errors.Wrap(err, "error listing BLOBs in source repository")
		}

		return nil
	})

	if err := eg.Wait(); err != nil {
		return nil, err //nolint:wrapcheck
	}

	c.finishSyncProcess()

	plan := &syncPlan{dstHasBlobs: len(dstMetadata) > 0}

	for _, sb := range srcBlobs {
		dstInfo, exists := dstMetadata[sb.id]
		delete(dstMetadata, sb.id)

		if sb.info.length < 0 {
			// deferred: neither copy nor delete in this run.
			continue
		}

		m := sb.metadata()

		switch {
		case !exists:
			plan.addCopy(m)
		case c.repositorySyncUpdate && (sb.info.timestamp > dstInfo.timestamp || sb.info.length != dstInfo.length):
			plan.addCopy(m)
		case c.repositorySyncUpdate && strings.HasPrefix(string(sb.id), syncConfigBlobPrefix):
			// configuration blobs are mutable and timestamps from two different clocks
			// can't be trusted to order them; compare their (small) contents instead.
			plan.configToCheck = append(plan.configToCheck, m)
		default:
			plan.inSyncBlobs++
			plan.inSyncBytes += m.Length
		}
	}

	if c.repositorySyncDelete {
		for id, info := range dstMetadata {
			// found in dst, not in src since we were deleting from dst as we found a match.
			ph := syncPhaseOf(id)
			plan.toDelete[ph] = append(plan.toDelete[ph], blob.Metadata{BlobID: id, Length: info.length, Timestamp: time.Unix(0, info.timestamp)})
			plan.numDelete++
			plan.deleteBytes += info.length
		}
	}

	return plan, nil
}

// checkConfigBlobs compares configuration blobs whose metadata looks in sync
// byte by byte and schedules the ones that differ for copying.
func (c *commandRepositorySyncTo) checkConfigBlobs(ctx context.Context, src blob.Reader, dst blob.Storage, plan *syncPlan) error {
	for _, m := range plan.configToCheck {
		same, err := sameBlobContents(ctx, src, dst, m.BlobID)
		if err != nil {
			return err
		}

		if same {
			plan.inSyncBlobs++
			plan.inSyncBytes += m.Length
		} else {
			plan.addCopy(m)
		}
	}

	return nil
}

func sameBlobContents(ctx context.Context, src blob.Reader, dst blob.Reader, id blob.ID) (bool, error) {
	var srcData, dstData gather.WriteBuffer
	defer srcData.Close()
	defer dstData.Close()

	if err := src.GetBlob(ctx, id, 0, -1, &srcData); err != nil {
		if errors.Is(err, blob.ErrBlobNotFound) {
			// gone from source, nothing to copy.
			return true, nil
		}

		return false, errors.Wrapf(err, "error reading %v from source", id)
	}

	if err := dst.GetBlob(ctx, id, 0, -1, &dstData); err != nil {
		if errors.Is(err, blob.ErrBlobNotFound) {
			return false, nil
		}

		return false, errors.Wrapf(err, "error reading %v from destination", id)
	}

	return bytes.Equal(srcData.ToByteSlice(), dstData.ToByteSlice()), nil
}

func (c *commandRepositorySyncTo) beginSyncProgress() {
	c.syncProgressMutex.Lock()
	defer c.syncProgressMutex.Unlock()

	c.lastSyncProgressMsg = ""
	c.lastSyncProgressArgs = nil
	c.lastSyncProgressLen = 0

	c.nextSyncOutputTime.Reset()
}

func (c *commandRepositorySyncTo) outputSyncProgress(msg string, args ...any) {
	if !c.progress.Enabled() {
		return
	}

	c.syncProgressMutex.Lock()
	defer c.syncProgressMutex.Unlock()

	c.lastSyncProgressMsg = msg
	c.lastSyncProgressArgs = args

	if c.nextSyncOutputTime.ShouldOutput(syncProgressInterval) {
		c.printSyncProgressLocked(false)
	}
}

// printSyncProgressLocked formats and prints the latest progress message,
// padding it to overwrite a longer previous one.
func (c *commandRepositorySyncTo) printSyncProgressLocked(newline bool) {
	s := fmt.Sprintf(c.lastSyncProgressMsg, c.lastSyncProgressArgs...)
	n := len(s)

	if n < c.lastSyncProgressLen {
		s += strings.Repeat(" ", c.lastSyncProgressLen-n)
	}

	c.lastSyncProgressLen = n

	if newline {
		s += "\n"
	}

	c.out.printStderr("\r%v", s)
}

func (c *commandRepositorySyncTo) finishSyncProcess() {
	if !c.progress.Enabled() {
		return
	}

	c.syncProgressMutex.Lock()
	defer c.syncProgressMutex.Unlock()

	if c.lastSyncProgressMsg == "" {
		return
	}

	c.printSyncProgressLocked(true)
}

func (c *commandRepositorySyncTo) runSyncBlobs(ctx context.Context, src blob.Reader, dst blob.Storage, plan *syncPlan, blobcfg format.BlobStorageConfiguration) error {
	var (
		totalCopied stats.CountSum
		vanished    atomic.Int64
	)

	tt := timetrack.Start()

	for phase := range numSyncPhases {
		if err := c.forEachParallel(ctx, plan.toCopy[phase], func(ctx context.Context, m blob.Metadata) error {
			log(ctx).Debugf("Copying %v (%v bytes)...", m.BlobID, m.Length)

			found, err := c.syncCopyBlob(ctx, m, src, dst, blobcfg)
			if err != nil {
				return errors.Wrapf(err, "error copying %v", m.BlobID)
			}

			if !found {
				vanished.Add(1)
			}

			numBlobs, bytesCopied := totalCopied.Add(m.Length)
			eta := "unknown"
			speed := "-"

			if est, ok := tt.Estimate(float64(bytesCopied), float64(plan.copyBytes)); ok {
				eta = fmt.Sprintf("%v (%v)", est.Remaining, formatTimestamp(est.EstimatedEndTime))
				speed = units.BytesPerSecondsString(est.SpeedPerSecond)
			}

			c.outputSyncProgress("  Copied %v blobs (%v), Speed: %v, ETA: %v",
				numBlobs, units.BytesString(bytesCopied), speed, eta)

			return nil
		}); err != nil {
			return errors.Wrap(err, "error copying blobs")
		}
	}

	if n := vanished.Load(); n > 0 {
		return errors.Errorf("%v BLOBs disappeared from the source while copying (is maintenance or a snapshot running?); the destination may be incomplete and no BLOBs were deleted, run sync-to again", n)
	}

	for _, phase := range syncDeletePhaseOrder {
		if err := c.forEachParallel(ctx, plan.toDelete[phase], func(ctx context.Context, m blob.Metadata) error {
			log(ctx).Debugf("Deleting %v (%v bytes)...", m.BlobID, m.Length)

			return errors.Wrapf(syncDeleteBlob(ctx, m, dst), "error deleting %v", m.BlobID)
		}); err != nil {
			return errors.Wrap(err, "error deleting blobs")
		}
	}

	return nil
}

// forEachParallel runs fn for every item using the configured parallelism and
// returns once all of them have finished, or the first one failed.
func (c *commandRepositorySyncTo) forEachParallel(ctx context.Context, items []blob.Metadata, fn func(ctx context.Context, m blob.Metadata) error) error {
	if len(items) == 0 {
		return nil
	}

	eg, ctx := errgroup.WithContext(ctx)
	ch := sliceToChannel(ctx, items)

	for range max(c.repositorySyncParallelism, 1) {
		eg.Go(func() error {
			for m := range ch {
				if err := fn(ctx, m); err != nil {
					return err
				}
			}

			return nil
		})
	}

	return eg.Wait() //nolint:wrapcheck
}

func sliceToChannel(ctx context.Context, md []blob.Metadata) chan blob.Metadata {
	ch := make(chan blob.Metadata)

	go func() {
		defer close(ch)

		for _, it := range md {
			select {
			case ch <- it:
			case <-ctx.Done():
				return
			}
		}
	}()

	return ch
}

func (c *commandRepositorySyncTo) putOptions(id blob.ID, m blob.Metadata, blobcfg format.BlobStorageConfiguration) blob.PutOptions {
	var opt blob.PutOptions

	if c.repositorySyncTimes && !c.timesUnsupported.Load() {
		opt.SetModTime = m.Timestamp
	}

	if blobcfg.IsRetentionEnabled() && !c.retentionUnsupported.Load() {
		for _, prefix := range repo.GetLockingStoragePrefixes() {
			if strings.HasPrefix(string(id), string(prefix)) {
				opt.RetentionMode = blobcfg.RetentionMode
				opt.RetentionPeriod = blobcfg.RetentionPeriod

				break
			}
		}
	}

	return opt
}

// syncCopyBlob copies one blob and reports false if it no longer exists in the source.
func (c *commandRepositorySyncTo) syncCopyBlob(ctx context.Context, m blob.Metadata, src blob.Reader, dst blob.Storage, blobcfg format.BlobStorageConfiguration) (bool, error) {
	var data gather.WriteBuffer
	defer data.Close()

	if err := src.GetBlob(ctx, m.BlobID, 0, -1, &data); err != nil {
		if errors.Is(err, blob.ErrBlobNotFound) {
			log(ctx).Warnf("BLOB disappeared from source: %v", m.BlobID)
			return false, nil
		}

		return false, errors.Wrapf(err, "error reading blob '%v' from source", m.BlobID)
	}

	// everything other than configuration blobs is immutable, so a length that
	// differs from the listing means a truncated or corrupted read.
	if !strings.HasPrefix(string(m.BlobID), syncConfigBlobPrefix) && int64(data.Length()) != m.Length {
		return false, errors.Errorf("read %v bytes of blob '%v' from source, expected %v", data.Length(), m.BlobID, m.Length)
	}

	for {
		opt := c.putOptions(m.BlobID, m, blobcfg)

		err := dst.PutBlob(ctx, m.BlobID, data.Bytes(), opt)

		switch {
		case err == nil:
			return true, nil

		case !opt.SetModTime.IsZero() && errors.Is(err, blob.ErrSetTimeUnsupported):
			c.timesUnsupported.Store(true)
			c.timesWarning.Do(func() {
				log(ctx).Warn("destination repository does not support preserving modification times")
			})

		case opt.HasRetentionOptions() && errors.Is(err, blob.ErrUnsupportedPutBlobOption):
			c.retentionUnsupported.Store(true)
			c.retentionWarning.Do(func() {
				log(ctx).Warn("WARNING: the source repository uses object locking (retention), but the destination does not support it. " +
					"Copied BLOBs will NOT be protected, and the copy will refuse writes until retention is disabled on it.")
			})

		default:
			return false, errors.Wrapf(err, "error writing blob '%v' to destination", m.BlobID)
		}
	}
}

func syncDeleteBlob(ctx context.Context, m blob.Metadata, dst blob.Storage) error {
	err := dst.DeleteBlob(ctx, m.BlobID)

	if errors.Is(err, blob.ErrBlobNotFound) {
		return nil
	}

	return errors.Wrap(err, "error deleting blob")
}

// ensureRepositoriesHaveSameFormatBlob verifies that the destination either
// has no format blob or one belonging to the same repository as the source,
// and reports whether it has one. It never writes: a missing format blob is
// copied in the last sync phase, after all the data it describes.
func (c *commandRepositorySyncTo) ensureRepositoriesHaveSameFormatBlob(ctx context.Context, src blob.Reader, dst blob.Storage) (bool, error) {
	var srcData gather.WriteBuffer
	defer srcData.Close()

	if err := src.GetBlob(ctx, format.KopiaRepositoryBlobID, 0, -1, &srcData); err != nil {
		return false, errors.Wrap(err, "error reading format blob")
	}

	var dstData gather.WriteBuffer
	defer dstData.Close()

	if err := dst.GetBlob(ctx, format.KopiaRepositoryBlobID, 0, -1, &dstData); err != nil {
		if errors.Is(err, blob.ErrBlobNotFound) {
			if c.repositorySyncDestinationMustExist {
				return false, errors.New("destination repository does not have a format blob")
			}

			return false, nil
		}

		return false, errors.Wrap(err, "error reading destination repository format blob")
	}

	uniqueID1, err := parseUniqueID(srcData.Bytes())
	if err != nil {
		return false, errors.Wrap(err, "error parsing unique ID of source repository")
	}

	uniqueID2, err := parseUniqueID(dstData.Bytes())
	if err != nil {
		return false, errors.Wrap(err, "error parsing unique ID of destination repository")
	}

	if uniqueID1 == uniqueID2 {
		return true, nil
	}

	return false, errors.New("destination repository contains incompatible data")
}

func parseUniqueID(r gather.Bytes) (string, error) {
	var f struct {
		UniqueID string `json:"uniqueID"`
	}

	if err := json.NewDecoder(r.Reader()).Decode(&f); err != nil {
		return "", errors.Wrap(err, "invalid JSON")
	}

	if f.UniqueID == "" {
		return "", errors.New("unique ID not found")
	}

	return f.UniqueID, nil
}
